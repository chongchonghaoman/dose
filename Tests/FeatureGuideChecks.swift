import Foundation

@main struct FeatureGuideChecks {
    @MainActor static func main() {
        let suite = "LightTable.FeatureGuideChecks.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        var count = 0
        func expect(_ value: Bool, _ label: String) { precondition(value, label); count += 1 }
        let a = UUID(), b = UUID()
        defaults.set(["0.1.72", "0.1.73"], forKey: FeatureGuideState.seenKey)
        defaults.set(["0.1.72.initial", "0.1.73.trays-1"], forKey: FeatureGuideState.seenRevisionKey)
        let state = FeatureGuideState(defaults: defaults, version: "0.1.74")
        expect(state.available && !state.hasBeenPresented, "matching release starts unseen")
        state.presentAutomatically(in: a, ready: false)
        expect(state.phase == .idle, "busy/nonkey windows defer")
        state.presentAutomatically(in: a, ready: true)
        expect(state.isWelcome(in: a), "ready window claims card")
        expect(!state.hasBeenPresented, "claim is not presentation")
        state.presentAutomatically(in: b, ready: true)
        expect(state.owner == a, "second window cannot duplicate")
        state.didPresent(in: b)
        expect(!state.hasBeenPresented, "wrong window cannot acknowledge")
        state.finish(in: a)
        state.presentAutomatically(in: b, ready: true)
        expect(state.isWelcome(in: b), "closed unseen window does not lose card")
        state.didPresent(in: b); state.didPresent(in: b)
        expect(defaults.stringArray(forKey: FeatureGuideState.seenKey) == ["0.1.72", "0.1.73", "0.1.74"], "presentation persists once and keeps older records")
        expect(defaults.stringArray(forKey: FeatureGuideState.seenRevisionKey) == ["0.1.72.initial", "0.1.73.trays-1", "0.1.74.\(FeatureGuideState.contentRevision)"], "content revision persists once and keeps older records")
        state.beginTour(in: b); state.dismissWelcome(in: b)
        expect(state.step(in: b) == 0, "sheet dismissal preserves tour")
        state.advance(in: a)
        expect(state.step(in: b) == 0, "other window cannot advance")
        state.previous(in: b)
        expect(state.step(in: b) == 0, "back stops at first step")
        state.advance(in: b)
        expect(state.step(in: b) == 1, "take and return step")
        state.advance(in: b)
        expect(state.step(in: b) == 2, "tray deletion step")
        state.previous(in: b)
        expect(state.step(in: b) == 1, "back navigation")
        state.advance(in: b); state.advance(in: b)
        expect(state.step(in: b) == 3, "loupe step follows tray workflow")
        state.advance(in: b)
        expect(state.step(in: b) == 4, "close-view step")
        state.advance(in: b)
        expect(state.step(in: b) == 5, "zoom step remains visible until completion")
        state.advance(in: b)
        expect(state.phase == .idle && state.owner == nil, "completion releases window")
        let restarted = FeatureGuideState(defaults: defaults, version: "0.1.74")
        restarted.presentAutomatically(in: a, ready: true)
        expect(restarted.phase == .idle, "restart does not repeat")
        restarted.replay(in: a)
        expect(restarted.isWelcome(in: a), "help replays seen version")
        restarted.replay(in: b)
        expect(restarted.owner == a, "help does not steal other window")
        restarted.dismissWelcome(in: a)
        expect(restarted.phase == .idle, "close dismisses card")
        restarted.replay(in: a); restarted.beginTour(in: a); restarted.finish(in: a)
        expect(restarted.phase == .idle && restarted.hasBeenPresented, "skip does not reset seen record")
        let previousRelease = FeatureGuideState(defaults: defaults, version: "0.1.73")
        expect(!previousRelease.available, "old versions cannot show the current release guide")
        let unknown = FeatureGuideState(defaults: defaults, version: "0.1.75")
        unknown.presentAutomatically(in: a, ready: true); unknown.replay(in: a)
        expect(!unknown.available && unknown.phase == .idle, "unauthored future version stays quiet")
        expect(!unknown.hasBeenPresented, "seen versions isolated")
        expect(FeatureGuideState.tourStepCount == 6, "release has six authored steps")
        expect(FeatureGuideTarget.releaseTour(step: 0, loupeEnabled: false) == .trayImport, "import targets the current-tray import button")
        expect(FeatureGuideTarget.releaseTour(step: 1, loupeEnabled: false) == .viewingArea, "take and return targets the table")
        expect(FeatureGuideTarget.releaseTour(step: 2, loupeEnabled: false) == .trayTabs, "delete targets the tray labels")
        expect(FeatureGuideTarget.releaseTour(step: 3, loupeEnabled: false) == .loupe, "select step targets only the loupe button")
        expect(FeatureGuideTarget.releaseTour(step: 4, loupeEnabled: true) == .viewingArea, "space step targets the photo viewing area")
        expect(FeatureGuideTarget.releaseTour(step: 5, loupeEnabled: true) == .magnification, "zoom step targets the focal control")
        expect((3..<FeatureGuideState.tourStepCount).allSatisfy { FeatureGuideTarget.releaseTour(step: $0, loupeEnabled: false) == .loupe }, "disabled loupe points to the required button instead of a hidden control")
        expect((0...2).allSatisfy { FeatureGuideTarget.releaseTour(step: $0, loupeEnabled: false) == FeatureGuideTarget.releaseTour(step: $0, loupeEnabled: true) }, "tray targets do not depend on loupe mode")

        // Earlier test builds recorded only the short version. The new content must still appear once.
        defaults.set(["0.1.72", "0.1.73", "0.1.74"], forKey: FeatureGuideState.seenKey)
        defaults.set(["0.1.73.trays-1"], forKey: FeatureGuideState.seenRevisionKey)
        let upgraded = FeatureGuideState(defaults: defaults, version: "0.1.74")
        expect(!upgraded.hasBeenPresented, "earlier guide content does not suppress the new tray guide")
        upgraded.presentAutomatically(in: a, ready: true)
        expect(upgraded.isWelcome(in: a), "existing test users receive new content")
        upgraded.finish(in: a)
        expect(!upgraded.hasBeenPresented, "unrendered revision is not acknowledged")
        upgraded.presentAutomatically(in: b, ready: true)
        upgraded.didPresent(in: b)
        expect(upgraded.hasBeenPresented, "rendered revision is acknowledged")
        expect(defaults.stringArray(forKey: FeatureGuideState.seenKey) == ["0.1.72", "0.1.73", "0.1.74"], "upgrading keeps version history without duplicates")
        expect(defaults.stringArray(forKey: FeatureGuideState.seenRevisionKey) == ["0.1.73.trays-1", "0.1.74.\(FeatureGuideState.contentRevision)"], "upgrading preserves previous content records")
        upgraded.finish(in: b)
        let upgradedRestart = FeatureGuideState(defaults: defaults, version: "0.1.74")
        upgradedRestart.presentAutomatically(in: a, ready: true)
        expect(upgradedRestart.phase == .idle, "new tray content is not repeated on restart")
        print("Feature guide: \(count) checks passed")
    }
}
