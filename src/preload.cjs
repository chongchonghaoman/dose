const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('lighttable', {
  load: () => ipcRenderer.invoke('state:load'),
  save: state => ipcRenderer.invoke('state:save', state),
  preferences: () => ipcRenderer.invoke('ui-preferences:load'),
  savePreferences: partial => ipcRenderer.invoke('ui-preferences:save', partial),
  pick: folder => ipcRenderer.invoke('photos:pick', Boolean(folder)),
  drop: files => ipcRenderer.invoke('photos:drop', files.map(file => webUtils.getPathForFile(file)).filter(Boolean)),
  fullscreen: enabled => ipcRenderer.invoke('window:fullscreen', enabled),
  export: state => ipcRenderer.invoke('layout:export', state),
  open: () => ipcRenderer.invoke('layout:open'),
  newTable: () => ipcRenderer.invoke('layout:new'),
  filmStatus: () => ipcRenderer.invoke('film:status'),
  spectralStatus: () => ipcRenderer.invoke('film:spectral-status'),
  openReferenceEditor: ids => ipcRenderer.invoke('reference:open',ids),
  onReferenceResult: fn => {const listener=(_,result)=>fn(result);ipcRenderer.on('reference:result',listener);return()=>ipcRenderer.removeListener('reference:result',listener);},
  spectralPreview: request => ipcRenderer.invoke('film:spectral-preview',request),
  autoFit: request => ipcRenderer.invoke('film:auto-fit',request),
  previewLut: hash => ipcRenderer.invoke('film:preview-lut',hash),
  importLut: () => ipcRenderer.invoke('film:import'),
  exportPhotos: (ids,format) => ipcRenderer.invoke('photos:export',ids,format),
  photoAvailability: ids => ipcRenderer.invoke('photos:availability',ids),
  chooseGridOutput: () => ipcRenderer.invoke('grid:choose-output'),
  exportGrid: request => ipcRenderer.invoke('grid:write',request),
  openExportFolder: () => ipcRenderer.invoke('photos:open-export'),
  openFilmResource: key => ipcRenderer.invoke('film:resource',key),
  onProgress: fn => ipcRenderer.on('import-progress', (_, p) => fn(p)),
  onClose: fn => ipcRenderer.on('before-close', fn)
});
